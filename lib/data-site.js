// Función para obtener noticias filtradas
export const getFilteredNews = (category = "all", limit = 6, offset = 0) => {
  let filteredNews = newsData;

  if (category !== "all") {
    // Mapeo de IDs de categoría a nombres de categoría
    const categoryMap = {
      tendencias: "Tendencias",
      lanzamientos: "Lanzamientos",
      "categoria-y": "Categoria Y",
    };

    const categoryName = categoryMap[category];
    if (categoryName) {
      filteredNews = newsData.filter((news) => news.category === categoryName);
    }
  }

  const total = filteredNews.length;
  const paginatedNews = filteredNews.slice(offset, offset + limit);

  return {
    news: paginatedNews,
    total,
    hasMore: offset + limit < total,
  };
};

// Función para obtener artículos destacados
export const getFeaturedNews = () => {
  return newsData.filter((news) => news.featured === true);
};

// Función para obtener una noticia por slug
export const getNewsBySlug = (slug) => {
  return newsData.find((news) => news.slug === slug);
};
